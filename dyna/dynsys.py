class CompositeSystem(DynamicalSystem):
    """
    A `DynamicalSystem` assembled from other `DynamicalSystem`s according to a
    graph-tool directed graph describing which named outputs feed which named
    inputs. Since it subclasses `DynamicalSystem`, a composite can itself be
    merged/connected into a larger composite (arbitrary nesting).

    You normally build these via `merge(...)` or `connect(...)` below rather
    than calling this constructor directly, but you can do so by having a properly
    built graph with:
    -- "system_name" vertex_property containing the names of the vertices (no need to 
    recursively add the subsystem names).
    -- "mapping" edge_property containing the pair (in_variable, out_variable) of
    each connection between the systems.
    """

    def __init__(self, name: str, subsystems: Sequence[DynamicalSystem], graph: "gt.Graph"):
        self.subsystems = list(subsystems)
        self._sys_by_name = {s.name: s for s in self.subsystems}
        if len(self._sys_by_name) != len(self.subsystems):
            raise ValueError("subsystem names must be unique")
        self.graph = graph

        vprop = graph.vertex_properties["system_name"]
        eprop = graph.edge_properties["mapping"]

        # Canonical ordering is the order of `subsystems`, independent of
        # however graph-tool happens to iterate its own vertices.
        state_offset: Dict[str, int] = {}
        off = 0
        for s in self.subsystems:
            state_offset[s.name] = off
            off += s.state_size
        N = off

        input_offset: Dict[str, int] = {}
        off = 0
        for s in self.subsystems:
            input_offset[s.name] = off
            off += s.input_size
        M = off

        # G[j] = index into concatenate([x_global (len N), u_ext_full (len M)])
        # telling where global input-slot j actually gets its value from.
        # Default: identity (slot j reads from u_ext_full[j], i.e. index N + j).
        G = np.arange(N, N + M, dtype=np.int32)
        covered_dst: set = set()

        for e in graph.edges():
            src_name = vprop[e.source()]
            dst_name = vprop[e.target()]
            src_var, dst_var = eprop[e]
            src_sys = self._sys_by_name[src_name]
            dst_sys = self._sys_by_name[dst_name]

            if not src_sys.has_output_var(src_var):
                raise ValueError(f"'{src_var}' is not a declared output of system '{src_name}'")
            if not dst_sys.has_input(dst_var):
                raise ValueError(f"'{dst_var}' is not a declared input of system '{dst_name}'")

            s0, s1 = src_sys.state_slice(src_var)
            d0, d1 = dst_sys.input_slice(dst_var)
            if (s1 - s0) != (d1 - d0):
                raise ValueError(
                    f"size mismatch wiring {src_name}.{src_var} (size {s1 - s0}) -> "
                    f"{dst_name}.{dst_var} (size {d1 - d0})"
                )

            global_src = np.arange(state_offset[src_name] + s0, state_offset[src_name] + s1)
            global_dst = np.arange(input_offset[dst_name] + d0, input_offset[dst_name] + d1)

            for gd in global_dst.tolist():
                if gd in covered_dst:
                    raise ValueError(
                        f"input '{dst_var}' of system '{dst_name}' is wired more than once"
                    )
                covered_dst.add(gd)
            G[global_dst] = global_src

        # Which global input slots remain free (unconnected) -> these become
        # this composite's own exposed input_vars, in subsystem/var order.
        free_ranges: List[Tuple[int, int]] = []
        input_vars: List[VarSpec] = []
        for s in self.subsystems:
            for v in s.input_vars:
                lo, hi = s.input_slice(v.name)
                slot0 = input_offset[s.name] + lo
                if slot0 not in covered_dst:
                    free_ranges.append((slot0, slot0 + v.size))
                    input_vars.append(VarSpec(f"{s.name}.{v.name}", v.size))

        free_slot_indices = (
            np.concatenate([np.arange(a, b) for a, b in free_ranges])
            if free_ranges else np.zeros((0,), dtype=np.int32)
        )

        state_vars = [
            VarSpec(f"{s.name}.{v.name}", v.size) for s in self.subsystems for v in s.state_vars
        ]
        outputs = [f"{s.name}.{o}" for s in self.subsystems for o in s.outputs]

        domains = {s.domain for s in self.subsystems}
        domain: Domain = domains.pop() if len(domains) == 1 else "hybrid"
        if domain == "hybrid":
            warnings.warn(
                f"CompositeSystem '{name}' mixes continuous and discrete subsystems "
                f"(domain='hybrid'). This framework only assembles the dynamics "
                f"function; you are responsible for integrating each part correctly."
            )

        default_params = {s.name: s.default_params for s in self.subsystems}

        # Stash precomputed, static (numpy/jax) layout info before calling
        # super().__init__, which will invoke self._composite_fn via self.fn.
        self._N, self._M = N, M
        self._state_offset = state_offset
        self._input_offset = input_offset
        self._G = jnp.asarray(G)
        self._free_slot_indices = jnp.asarray(free_slot_indices, dtype=jnp.int32)

        super().__init__(
            name=name,
            state_vars=state_vars,
            input_vars=input_vars,
            outputs=outputs,
            params=default_params,
            domain=domain,
            fn=self._composite_fn,
        )

    def _composite_fn(self, x_global: jnp.ndarray, u_free: jnp.ndarray,
                       params: Dict[str, Any], t: Any) -> jnp.ndarray:
        # Set variables to 0 and to u_free
        u_ext_full = jnp.zeros((self._M,), dtype=x_global.dtype).at[self._free_slot_indices].set(u_free)
        augmented = jnp.concatenate([x_global, u_ext_full])
        eff_u = augmented[self._G]

        dxs = []
        # This is the meat: 
        # The indexes, both of the state and of the inputs, are necessary to properly pass the variables to the single subsystems
        for s in self.subsystems:
            x0 = self._state_offset[s.name]
            x1 = x0 + s.state_size
            u0 = self._input_offset[s.name]
            u1 = u0 + s.input_size
            xi = x_global[x0:x1]
            ui = eff_u[u0:u1]
            pi = params.get(s.name, None) # TODO: could be obscure: will use default parameters for all unspecified subsystems 
            dxs.append(s(xi, ui, pi, t)) # this uses the __call__ of the subsystem; should it use s.fn instead? I think not
        return jnp.concatenate(dxs) if dxs else jnp.zeros((0,), dtype=x_global.dtype)

    def flatten_params(self, params: Optional[Any] = None, _prefix: str = "") -> Dict[str, Any]:
        """
        Collapse the nesting `_composite_fn` needs -- one dict level per
        composed CompositeSystem -- into a single dict keyed by dotted
        subsystem path, e.g. {"outer.inner.leaf1": {...}, "outer.leaf3": {...}}.
        Only the composition-induced nesting is removed; each *leaf*
        subsystem's own parameter pytree is kept as-is (not flattened
        further). `params` defaults to `self.default_params`.
        """
        if params is None:
            params = self.default_params
        flat: Dict[str, Any] = {}
        for s in self.subsystems:
            key = f"{_prefix}{s.name}"
            sub_params = params[s.name]
            if isinstance(s, CompositeSystem):
                flat.update(s.flatten_params(sub_params, _prefix=f"{key}."))
            else:
                flat[key] = sub_params
        return flat

    def unflatten_params(self, flat: Dict[str, Any], _prefix: str = "",
                          _missing: Optional[List[str]] = None) -> Any:
        """Inverse of `flatten_params`: rebuild the nested dict that `self.fn`
        (i.e. `_composite_fn`) actually expects as its `params` argument.
        If `flat` is missing any leaf subsystem's key, raises a single
        KeyError listing *all* of them (not just the first one found)."""
        top_level = _missing is None
        if top_level:
            _missing = []
 
        nested: Dict[str, Any] = {}
        for s in self.subsystems:
            key = f"{_prefix}{s.name}"
            if isinstance(s, CompositeSystem):
                nested[s.name] = s.unflatten_params(flat, _prefix=f"{key}.", _missing=_missing)
            elif key in flat:
                nested[s.name] = flat[key]
            else:
                _missing.append(key)
                nested[s.name] = None  # placeholder; discarded below via the raise
 
        if top_level and _missing:
            raise KeyError(f"missing flat param key(s): {sorted(_missing)}")
        return nested

    # convenience: pull a named subsystem's own slice back out of the
    # composite's global state/output, e.g. for plotting/inspection.
    def subsystem_state(self, x_global: jnp.ndarray, sys_name: str) -> jnp.ndarray:
        s = self._sys_by_name[sys_name]
        a = self._state_offset[sys_name]
        return x_global[a:a + s.state_size]

    def autonomize(
        self,
        submodules: Optional[Sequence[str]] = None,
        clock: Optional[DynamicalSystem] = None,
        clock_output: Optional[str] = None,
        input_name: str = "t_in",
        name: Optional[str] = None,
    ) -> "CompositeSystem":
        """
        CompositeSystem-specific override of `DynamicalSystem.autonomize`.
 
        Recursively wires a shared `clock` into the named `submodules`,
        wherever they live inside this composite -- at any nesting depth.
        Each matched node is adapted via the base (leaf-level)
        `DynamicalSystem.autonomize(input_name)`, exactly as you'd do by
        hand for one system; a matched name that is itself a nested
        CompositeSystem is adapted as a whole, so the entire subtree beneath
        it ends up sharing that one substituted time.
 
        Unlike the generic `DynamicalSystem.autonomize` (which flattens
        everything down into one opaque `fn`), this always goes back through
        `connect()`, so the result is a genuine `CompositeSystem` -- `.graph`
        and `.subsystems` stay intact. This replaces the old standalone
        `connect_clock(...)` function; call it as `composite.autonomize(...)`.
 
        submodules : names of the subsystems to clock, at any nesting depth.
                     None (default) means every *immediate* child of this
                     composite.
        clock      : a DynamicalSystem exposing time as its output, e.g.
                     built with `make_clock(...)`. Required.
        """
        if clock is None:
            raise ValueError(
                "CompositeSystem.autonomize(...) requires a `clock` system "
                "(e.g. built with make_clock(...))"
            )
 
        top_children, top_edges = _unpack(self)
        base_name = name or self.name
 
        target_names = set(submodules) if submodules is not None else {c.name for c in top_children}
 
        if clock_output is None:
            if len(clock.outputs) != 1:
                raise ValueError(
                    f"clock '{clock.name}' has {len(clock.outputs)} outputs; "
                    f"pass clock_output explicitly to disambiguate"
                )
            clock_output = clock.outputs[0]
 
        new_top_children, new_edges, matched = [], list(top_edges), set()
        for child in top_children:
            new_child, bubbled, child_matched = _wire_clock_recursive(child, target_names, input_name)
            matched |= child_matched
            for local_name in bubbled:
                new_edges.append((clock.name, clock_output, new_child.name, local_name))
            new_top_children.append(new_child)
 
        missing = target_names - matched
        if missing:
            raise ValueError(f"submodule(s) not found (recursively): {sorted(missing)}")
 
        return connect([clock] + new_top_children, new_edges, name=base_name)

    def promote_params(
        self,
        targets: Union[Sequence[str], Dict[str, Optional[Sequence[str]]]],
        state_prefix: str = "",
        name: Optional[str] = None,
    ) -> "CompositeSystem":
        """
        CompositeSystem-specific override of
        `DynamicalSystem.promote_params`: recursively promote
        parameters of NAMED subsystems -- at any nesting depth -- into
        ordinary state variables with trivial dynamics (dx/dt = 0, or
        x_next = x for discrete subsystems), while still returning a genuine
        CompositeSystem (`.graph`/`.subsystems` preserved, since this goes
        back through `connect()` at the end).
 
        targets : either
          - a plain sequence of subsystem names -> promote ALL of each named
            subsystem's own parameters, or
          - a dict {subsystem_name: param_names_or_None} -> promote just the
            given parameter names for that subsystem (None means "all",
            same as the base method's default).
 
        Each matched subsystem is adapted via the base, leaf-level
        `DynamicalSystem.promote_params(...)` (called explicitly on
        the base class, bypassing this override -- same reasoning as the
        sibling `promote_params`/`autonomize` overrides). The newly-promoted
        state is appended after each subsystem's existing state, so existing
        state/output indices elsewhere are unaffected; get matching initial
        values via `.promoted_initial_state(...)` on the ORIGINAL subsystem.
        """
        target_map: Dict[str, Optional[Sequence[str]]] = (
            dict(targets) if isinstance(targets, dict) else {t: None for t in targets}
        )
 
        top_children, top_edges = _unpack(self)
        base_name = name or self.name
 
        new_top_children: List[DynamicalSystem] = []
        matched: set = set()
        for child in top_children:
            new_child, child_matched = _promote_params_recursive(child, target_map, state_prefix)
            matched |= child_matched
            new_top_children.append(new_child)
 
        missing = set(target_map) - matched
        if missing:
            raise ValueError(f"subsystem(s) not found (recursively): {sorted(missing)}")
 
        return connect(new_top_children, top_edges, name=base_name)


