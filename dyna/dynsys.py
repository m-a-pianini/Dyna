class DynamicalSystem:
    """
    A single dynamical system.

    Parameters
    ----------
    name : unique identifier (used when composing systems together)
    state_vars : ordered named/sized blocks making up the state vector x
    fn : f(x, u, p, t) -> dx_or_xnext, same shape as x.
         `u` is always provided (shape (0,) if input_vars is empty).
    input_vars : ordered named/sized blocks making up the (optional) input vector u
    outputs : subset of state_vars' *names* exposed to other systems when composing
    params : a JAX pytree of default parameters (e.g. a dict of jnp arrays)
    domain : 'continuous' (dx/dt = f(...)) or 'discrete' (x_next = f(...))
    """

    def __init__(
        self,
        name: str,
        state_vars: Sequence[VarSpec],
        fn: Callable[[jnp.ndarray, jnp.ndarray, Any, Any], jnp.ndarray],
        input_vars: Sequence[VarSpec] = (),
        outputs: Sequence[str] = (),
        params: Any = None,
        domain: Domain = "continuous",
    ):
        state_vars = tuple(state_vars)
        input_vars = tuple(input_vars)
        outputs = tuple(outputs)

        state_names = {v.name for v in state_vars}
        if len(state_names) != len(state_vars):
            raise ValueError(f"[{name}] duplicate state variable names")
        input_names = {v.name for v in input_vars}
        if len(input_names) != len(input_vars):
            raise ValueError(f"[{name}] duplicate input variable names")
        for o in outputs:
            if o not in state_names:
                raise ValueError(
                    f"[{name}] output '{o}' must be one of this system's state_vars "
                    f"{sorted(state_names)} (outputs are always a subset of the state)"
                )
        if domain not in ("continuous", "discrete", "hybrid"):
            raise ValueError("domain must be 'continuous', 'discrete', or 'hybrid'")

        if not isinstance(params, dict):
            raise TypeError(
                f"DynamicalSystems requires a dict of params, "
                f"got {type(params).__name__}"
            )

        self.name = name
        self.state_vars = state_vars
        self.input_vars = input_vars
        self.outputs = outputs
        self.fn = fn
        self.default_params = params
        self.domain = domain

        self._state_by_name = {v.name: v for v in state_vars}
        self._input_by_name = {v.name: v for v in input_vars}
        self._state_slices, self.state_size = _layout(state_vars)
        self._input_slices, self.input_size = _layout(input_vars)

    # -- introspection -----------------------------------------------------

    def has_input(self, name: str) -> bool:
        return name in self._input_slices

    def has_output_var(self, name: str) -> bool:
        return name in self.outputs

    def state_slice(self, name: str) -> Tuple[int, int]:
        return self._state_slices[name]

    def input_slice(self, name: str) -> Tuple[int, int]:
        return self._input_slices[name]

    @property
    def output_indices(self) -> np.ndarray:
        """Indices into the state vector corresponding to (in order) `self.outputs`."""
        idxs: List[int] = []
        for o in self.outputs:
            a, b = self._state_slices[o]
            idxs.extend(range(a, b))
        return np.asarray(idxs, dtype=np.int32)

    @property
    def output_size(self) -> int:
        return int(self.output_indices.size)

    def get_output(self, x: jnp.ndarray) -> jnp.ndarray:
        if not self.outputs:
            return jnp.zeros((0,), dtype=x.dtype)
        return x[self.output_indices]

    def split_state(self, x: jnp.ndarray) -> Dict[str, jnp.ndarray]:
        return {name: x[a:b] for name, (a, b) in self._state_slices.items()}

    def split_input(self, u: jnp.ndarray) -> Dict[str, jnp.ndarray]:
        return {name: u[a:b] for name, (a, b) in self._input_slices.items()}

    def pack_state(self, d: Dict[str, Any]) -> jnp.ndarray:
        return jnp.concatenate([jnp.atleast_1d(jnp.asarray(d[v.name])) for v in self.state_vars])

    def pack_input(self, d: Dict[str, Any]) -> jnp.ndarray:
        if not self.input_vars:
            return jnp.zeros((0,))
        return jnp.concatenate([jnp.atleast_1d(jnp.asarray(d[v.name])) for v in self.input_vars])

    # -- evaluation ----------------------------------------------------------

    def __call__(self, x: jnp.ndarray, u: Optional[jnp.ndarray] = None,
                 p: Any = None, t: Any = 0.0) -> jnp.ndarray:
        if u is None:
            u = jnp.zeros((self.input_size,))
        if p is None:
            p = self.default_params
        return self.fn(x, u, p, t)

    # -- time handling ---------------------------------------------------------
 
    def autonomize(self, input_name: str = "t_in") -> "DynamicalSystem":
        """
        Expose this system's time dependence as an ordinary, wireable input
        variable instead of the implicit `t` argument -- without touching
        the original `fn`'s body. Appends `input_name` as a new (size-1)
        input; the `t` argument on the returned system's `fn` is ignored
        (time now arrives through `u`). This is what lets you `connect()` a
        shared clock (see `make_clock`) into this system's time input.
        """
        if input_name in self._input_by_name:
            raise ValueError(f"'{input_name}' is already an input variable of '{self.name}'")
 
        original_fn = self.fn
        m = self.input_size  # size of the *original* input vector, before appending time
 
        def fn(x: jnp.ndarray, u_aug: jnp.ndarray, p: Any, t: Any) -> jnp.ndarray:
            u, t_slot = u_aug[:m], u_aug[m]
            return original_fn(x, u, p, t_slot)
 
        return DynamicalSystem(
            name=self.name,
            state_vars=list(self.state_vars),
            fn=fn,
            input_vars=list(self.input_vars) + [VarSpec(input_name)],
            outputs=list(self.outputs),
            params=self.default_params,
            domain=self.domain,
        )

    # -- parameters shenanigans (Wiggins approved) ---------------------------

    def promote_params(self, param_names: Optional[Sequence[str]] = None,
                                 state_prefix: str = "") -> "DynamicalSystem":
        """
        Turn selected (or, by default, ALL) entries of this system's `params`
        into ordinary STATE variables with trivial dynamics -- dx/dt = 0
        (continuous) or x_next = x (discrete) -- instead of fixed parameters.
        The state-space analogue of `promote_params` (which does the same
        thing but as a wireable input); useful for treating a parameter as
        something to integrate/hold/inspect as state -- e.g. gradient-based
        parameter fitting through a single state vector, or slow parameter
        drift -- rather than something driven externally.
 
        `self.default_params` must be a flat dict of scalar/array leaves (see
        `CompositeSystem.promote_params_to_state` for targeting subsystems
        inside a composite instead). `param_names=None` (default) promotes
        every key; pass an explicit subset for "some". Each promoted
        parameter becomes a new state variable named f"{state_prefix}{name}",
        appended after the existing state (so existing state/output indices
        are unchanged) and sized to match the parameter's own (static)
        shape. The returned system's `default_params` no longer contains the
        promoted keys.
 
        Use `.promoted_initial_state(param_names)` -- called on THIS system,
        BEFORE promoting -- to get the matching initial-state block (the
        parameters' own default values, flattened) to append to your own
        initial condition.
        """
        if not isinstance(self.default_params, dict):
            raise TypeError(
                f"[{self.name}] promote_params requires a flat dict of params, "
                f"got {type(self.default_params).__name__}"
            )
        names = list(self.default_params) if param_names is None else list(param_names)
        unknown = set(names) - set(self.default_params)
        if unknown:
            raise ValueError(f"[{self.name}] unknown parameter name(s): {sorted(unknown)}")
        for n in names:
            if isinstance(self.default_params[n], dict):
                raise TypeError(
                    f"[{self.name}] parameter '{n}' is itself a nested params dict "
                    f"(likely a CompositeSystem's own subsystem params); "
                    f"promote_params only handles flat scalar/array parameter "
                    f"leaves -- target that subsystem directly (e.g. via "
                    f"CompositeSystem.promote_params) instead."
                )
        collide = [n for n in names if n in self._state_by_name]
        if collide:
            raise ValueError(
                f"[{self.name}] parameter name(s) already used as state variable(s): {collide}"
            )
 
        original_fn = self.fn
        n_orig = self.state_size
 
        shapes = {n: np.asarray(self.default_params[n]).shape for n in names}
        sizes = {n: int(np.atleast_1d(np.asarray(self.default_params[n])).size) for n in names}
        new_state_vars = [VarSpec(f"{state_prefix}{n}", sizes[n]) for n in names]
        total_promoted = sum(sizes.values())
        is_discrete = self.domain == "discrete"
 
        remaining_params = {k: v for k, v in self.default_params.items() if k not in names}
 
        def fn(x_aug: jnp.ndarray, u: jnp.ndarray, p: Any, t: Any) -> jnp.ndarray:
            x = x_aug[:n_orig]
            full_p = dict(p)
            offset = n_orig
            promoted_blocks = []
            for n in names:
                size = sizes[n]
                block = x_aug[offset:offset + size]
                promoted_blocks.append(block)
                full_p[n] = block.reshape(shapes[n])
                offset += size
            dx = original_fn(x, u, full_p, t)
            if is_discrete:
                trivial = (jnp.concatenate(promoted_blocks) if promoted_blocks
                           else jnp.zeros((0,), dtype=x_aug.dtype))
            else:
                trivial = jnp.zeros((total_promoted,), dtype=x_aug.dtype)
            return jnp.concatenate([dx, trivial])
 
        return DynamicalSystem(
            name=self.name,
            state_vars=list(self.state_vars) + new_state_vars,
            fn=fn,
            input_vars=self.input_vars,
            outputs=list(self.outputs),
            params=remaining_params,
            domain=self.domain,
        )
    
    # -- composition sugar ---------------------------------------------------

    def __or__(self, other: "DynamicalSystem") -> "CompositeSystem":
        return merge(self, other)

    def __rshift__(self, other: "DynamicalSystem") -> "CompositeSystem":
        return series(self, other)

    def __repr__(self) -> str:
        return (f"{type(self).__name__}(name={self.name!r}, domain={self.domain!r}, "
                f"state_size={self.state_size}, input_size={self.input_size}, "
                f"outputs={list(self.outputs)})")


