def build_graph(subsystems: Sequence[DynamicalSystem], edges: Sequence[Edge]) -> "gt.Graph":
    """
    Build a graph-tool directed graph: one vertex per subsystem, one edge per
    wired connection. `edges` is a list of
        (src_system_name, src_output_var, dst_system_name, dst_input_var)
    tuples. Vertex property 'system_name' and edge property 'mapping'
    (a (src_var, dst_var) tuple) carry the wiring information.
    """
    g = gt.Graph(directed=True)
    name_prop = g.new_vertex_property("object")
    vertex_of = {}
    names_seen = set()
    for s in subsystems:
        if s.name in names_seen:
            raise ValueError(f"duplicate subsystem name '{s.name}'")
        names_seen.add(s.name)
        v = g.add_vertex()
        name_prop[v] = s.name
        vertex_of[s.name] = v
    g.vertex_properties["system_name"] = name_prop

    mapping_prop = g.new_edge_property("object")
    for (src_name, src_var, dst_name, dst_var) in edges:
        if src_name not in vertex_of:
            raise ValueError(f"unknown source system '{src_name}' in edge list")
        if dst_name not in vertex_of:
            raise ValueError(f"unknown destination system '{dst_name}' in edge list")
        e = g.add_edge(vertex_of[src_name], vertex_of[dst_name])
        mapping_prop[e] = (src_var, dst_var)
    g.edge_properties["mapping"] = mapping_prop
    return g


