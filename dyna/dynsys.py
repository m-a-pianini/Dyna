def connect(subsystems: Sequence[DynamicalSystem], edges: Sequence[Edge],
            name: str = "composite") -> CompositeSystem:
    """
    Wire `subsystems` together according to `edges`, a list of
        (src_system_name, src_output_var, dst_system_name, dst_input_var)
    tuples, and return one CompositeSystem. `edges` may describe any directed
    graph topology, including cycles (feedback loops) -- see module docstring
    for why cycles are safe here.
    """
    g = build_graph(subsystems, edges)
    return CompositeSystem(name, subsystems, g)


def merge(*subsystems: DynamicalSystem, name: str = "merged") -> CompositeSystem:
    """
    Block-diagonal composition: concatenate every state/input/param, with NO
    coupling between subsystems -- each keeps evolving under its own,
    independent dynamics function. Equivalent to `connect(subsystems, [])`.
    """
    g = build_graph(subsystems, edges=[])
    return CompositeSystem(name, subsystems, g)


def series(a: DynamicalSystem, b: DynamicalSystem, name: Optional[str] = None) -> CompositeSystem:
    """
    Convenience cascade: auto-wire every output of `a` to the identically
    *named* (and same-sized) input of `b`. For fan-out, feedback, or more
    than two systems, use `connect(...)` directly with an explicit edge list.
    """
    edges: List[Edge] = []
    for o in a.outputs:
        if b.has_input(o):
            a_size = a._state_by_name[o].size
            b_size = b._input_by_name[o].size
            if a_size == b_size:
                edges.append((a.name, o, b.name, o))
    if not edges:
        raise ValueError(
            f"series(): no matching same-name/same-size output(of '{a.name}') -> "
            f"input(of '{b.name}') pairs found; use connect(...) explicitly."
        )
    return connect([a, b], edges, name=name or f"{a.name}_then_{b.name}")


def make_clock(name: str = "clock", rate: float = 1.0, domain: Domain = "continuous") -> DynamicalSystem:
    """
    A trivial autonomous system whose sole state variable *is* time itself:
        continuous:  d(tau)/dt = rate           (rate=1 recovers ordinary time)
        discrete:    tau_next  = tau + rate      (rate=1 recovers the step index)
    Its output is that same state, so -- unlike the special-cased `t` argument
    on ordinary systems -- it's an ordinary wireable output and can be fanned
    out via `connect()` to any number of other subsystems that read time
    through a normal *input* variable instead of through the `t` argument.
    Useful when several composed subsystems should share one common clock.
    """
    is_continuous = domain == "continuous"
 
    def fn(x, u, p, t):
        if is_continuous:
            return jnp.ones((1,), dtype=x.dtype) * p["rate"]
        return x + p["rate"]
 
    return DynamicalSystem(
        name=name,
        state_vars=[VarSpec("tau")],
        outputs=["tau"],
        params={"rate": rate},
        domain=domain,
        fn=fn,
    ) 
